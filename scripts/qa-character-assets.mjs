import { access, mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { inspectPngFrame } from "./lib/png-frame-qa.mjs";

const rootDir = resolve(import.meta.dirname, "..");
const reportPath = resolve(rootDir, "reports/pre-db-character-readiness.md");

const pets = [
  { id: "akkigae", name: "아끼개", species: "dog" },
  { id: "ttoosseunyang", name: "또쓰냥", species: "cat" },
  { id: "kangchongmu", name: "깡총무", species: "rabbit" },
];

const expressions = ["neutral", "happy", "sad", "wink", "surprised", "sleepy"];
const items = ["hat", "crown", "sunglasses", "ribbon", "scarf", "wings"];

await mkdir(resolve(rootDir, "reports"), { recursive: true });

const rows = [];
const failures = [];
const warnings = [];

for (const pet of pets) {
  const imagePath = `public/assets/pets/base-body-standard/${pet.id}.png`;
  const absoluteImagePath = resolve(rootDir, imagePath);
  const imageExists = await exists(absoluteImagePath);
  let frameStatus = "FAIL";
  let frameNotes = "missing base body";

  if (imageExists) {
    const buffer = await readFile(absoluteImagePath);
    const qa = inspectPngFrame(buffer);
    frameStatus = qa.status;
    frameNotes = `${qa.boundsText}; ${qa.notes.join("; ")} ${qa.warnings.join("; ")}`.trim();
    if (!qa.passed) failures.push(`${pet.id} frame QA failed: ${qa.notes.join("; ")}`);
    qa.warnings.forEach((warning) => warnings.push(`${pet.id} frame warning: ${warning}`));
  } else {
    failures.push(`${pet.id} missing ${imagePath}`);
  }

  const missingExpressions = [];
  for (const expression of expressions) {
    const expressionPath = resolve(rootDir, `public/assets/pet-parts/${pet.id}/${expression}.svg`);
    if (!(await exists(expressionPath))) missingExpressions.push(expression);
  }

  if (missingExpressions.length) {
    failures.push(`${pet.id} missing expressions: ${missingExpressions.join(", ")}`);
  }

  rows.push(
    `| ${pet.id} | ${pet.name} | ${pet.species} | ${imageExists ? "present" : "missing"} | ${frameStatus} | ${
      missingExpressions.length ? missingExpressions.join(", ") : "complete"
    } | ${frameNotes} |`,
  );
}

const report = `# Pre-DB Character Readiness Report

Generated by \`npm run character:qa\`.

This report covers work that can be finished before database integration. It checks local character assets, expression coverage, and the fixed-frame PNG contract. It does not replace visual QA in the browser.

## Summary

- Pets checked: ${pets.length}
- Expressions required per pet: ${expressions.length}
- Wearable items requiring visual QA: ${items.length}
- Failures: ${failures.length}
- Warnings: ${warnings.length}

## Asset Matrix

| Pet ID | Name | Species | Base Body | Frame QA | Expressions | Notes |
| --- | --- | --- | --- | --- | --- | --- |
${rows.join("\n")}

## Wearable QA Matrix

The following matrix must be visually approved before photo-based generation testing:

| Pet | Items |
| --- | --- |
${pets.map((pet) => `| ${pet.id} | ${items.join(", ")} |`).join("\n")}

## Failures

${failures.length ? failures.map((failure) => `- ${failure}`).join("\n") : "- None"}

## Warnings

${warnings.length ? warnings.map((warning) => `- ${warning}`).join("\n") : "- None"}

## Pre-DB Done Criteria

- [x] Fixed-frame full base-body generation script exists.
- [x] Local frame QA exists for generated PNG assets.
- [x] Required expression asset coverage is checked.
- [x] Wearable item matrix is documented for manual visual QA.
- [ ] Every generated character is visually approved in \`public/interaction-preview.html\`.
- [ ] Every wearable item is visually approved for every preset character.
- [ ] Photo-based generation produces a standard-v1 base body and passes this same QA.
`;

await writeFile(reportPath, report);
console.log(report.replace(/\n## Asset Matrix[\s\S]*/, ""));
console.log(`Saved ${reportPath}`);

if (failures.length) {
  process.exitCode = 1;
}

async function exists(path) {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}
